// Generates web/src/theme.css: every colour the UI uses as an RGB CSS variable, for light and dark mode.
// Pages keep using normal Tailwind names (slate-500, red-50, brand-600 …); tailwind.config.js maps them to these
// variables, so the whole app switches theme by toggling the `dark` class on <html>.
// Run: node web/scripts/gen-theme.mjs   (re-run after changing a palette below)
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import colors from "tailwindcss/colors.js";

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

// "Paper": warm, slightly ivory neutrals instead of cold slate. 50 = page, 900 = ink.
const paper = { 50: "#f8f7f4", 100: "#f1efea", 200: "#e5e2db", 300: "#d2cec5", 400: "#9f9a90", 500: "#67635b",
  600: "#514e47", 700: "#3e3b36", 800: "#292724", 900: "#191816", 950: "#0e0d0c" };
// "Night ink": the dark theme neutrals, a deep blue-black. 50 = page, 900 = text.
const night = { 50: "#0e1218", 100: "#151a22", 200: "#202631", 300: "#2e3644", 400: "#687182", 500: "#9aa3b1",
  600: "#b4bbc6", 700: "#ccd2da", 800: "#e1e5eb", 900: "#f1f3f6", 950: "#fafbfc" };
// Office navy (house style #1F3864 = 600).
const brand = { 50: "#eef2f9", 100: "#d9e1f0", 200: "#b5c5e2", 300: "#87a1cf", 400: "#5679b6", 500: "#2d5aa0",
  600: "#1f3864", 700: "#172a4c", 800: "#111f38", 900: "#0b1526", 950: "#060c16" };
const brandDark = { 50: "#141d2e", 100: "#1a2740", 200: "#24365a", 300: "#33497a", 400: "#5b7fc0", 500: "#8fb0ea",
  600: "#3d63a8", 700: "#4a72b8", 800: "#b9cdf2", 900: "#dce6f8", 950: "#eef3fc" };
// Seal: the brass/gold of a certification stamp. Used only for certification moments (stamp, approve, released).
const seal = { 50: "#fbf6ea", 100: "#f5e9c9", 200: "#ead293", 300: "#ddb862", 400: "#cc9d3c", 500: "#b5832a",
  600: "#966a1c", 700: "#775317", 800: "#5c4015", 900: "#3e2b0f", 950: "#241806" };
const sealDark = { 50: "#221b0f", 100: "#2e2412", 200: "#4a3a1a", 300: "#6d5522", 400: "#a9832f", 500: "#d6ac52",
  600: "#c99a3c", 700: "#e2c27a", 800: "#efd9a6", 900: "#f8ecd0", 950: "#fcf6e8" };

const hexToRgb = (h) => { const n = parseInt(h.slice(1), 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; };
const mix = (a, b, w) => a.map((v, i) => Math.round(v * (1 - w) + b[i] * w));
const rgb = (arr) => arr.join(" ");

// Dark variant of a Tailwind status palette: light tints become dark tints over the night page, strong shades lighten.
function darken(pal) {
  const bg = hexToRgb(night[50]);
  const base = hexToRgb(pal[500]);
  const out = {
    50: mix(bg, base, 0.12), 100: mix(bg, base, 0.18), 200: mix(bg, base, 0.32), 300: mix(bg, base, 0.5),
    400: hexToRgb(pal[400]), 500: hexToRgb(pal[400]), 600: hexToRgb(pal[300]), 700: hexToRgb(pal[300]),
    800: hexToRgb(pal[200]), 900: hexToRgb(pal[100]), 950: hexToRgb(pal[50]),
  };
  return Object.fromEntries(SHADES.map((s) => [s, rgb(out[s])]));
}
const asVars = (pal) => Object.fromEntries(SHADES.map((s) => [s, rgb(hexToRgb(pal[s]))]));

const STATUS = ["red", "amber", "green", "emerald", "blue", "violet"];
const light = { slate: asVars(paper), brand: asVars(brand), seal: asVars(seal) };
const dark = { slate: asVars(night), brand: asVars(brandDark), seal: asVars(sealDark) };
for (const c of STATUS) { light[c] = asVars(colors[c]); dark[c] = darken(colors[c]); }

const block = (pals, extra) => [
  ...Object.entries(pals).flatMap(([name, p]) => SHADES.map((s) => `  --c-${name}-${s}: ${p[s]};`)),
  ...Object.entries(extra).map(([k, v]) => `  --c-${k}: ${v};`),
].join("\n");

const css = `/* Generated by web/scripts/gen-theme.mjs. Do not edit by hand. */
:root {
${block(light, { surface: "255 255 255", raised: "255 255 255", sidebar: rgb(hexToRgb("#f1efea")) })}
  color-scheme: light;
}
:root.dark {
${block(dark, { surface: rgb(hexToRgb("#141922")), raised: rgb(hexToRgb("#1a202a")), sidebar: rgb(hexToRgb("#0b0f14")) })}
  color-scheme: dark;
}
`;
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../src/theme.css");
writeFileSync(out, css);
console.log("wrote", out);
